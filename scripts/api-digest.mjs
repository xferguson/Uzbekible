// Generates docs/api.md: one line per public export of each src/core/<module> and src/ui entry point.
// `npm run api` writes it; `npm run api -- --check` exits 1 when the committed file is stale.
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'docs', 'api.md');
const MAX_LEN = 220;

const DEFAULT_OPTIONS = {
  target: ts.ScriptTarget.ES2022,
  module: ts.ModuleKind.ESNext,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  strict: true,
  skipLibCheck: true,
  noEmit: true,
  types: [],
};

const squash = (s) => s.replace(/\s+/g, ' ').trim();
const clip = (s) => (s.length > MAX_LEN ? `${s.slice(0, MAX_LEN - 1)}…` : s);
const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

function describeSymbol(checker, exported) {
  const symbol = exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported;
  const name = exported.getName();
  const decl = symbol.declarations?.[0];
  if (!decl) return null;
  const doc = squash(ts.displayPartsToString(symbol.getDocumentationComment(checker)).split('\n')[0] ?? '');
  const tail = doc ? ` - ${doc}` : '';
  const type = checker.getTypeOfSymbolAtLocation(symbol, decl);
  const calls = checker.getSignaturesOfType(type, ts.SignatureKind.Call);
  const isValue = symbol.flags & ts.SymbolFlags.Value;
  const sig = (s) => `${name}${checker.signatureToString(s, decl, ts.TypeFormatFlags.NoTruncation)}`;

  let body;
  if (ts.isInterfaceDeclaration(decl)) {
    const tp = decl.typeParameters ? `<${decl.typeParameters.map((t) => t.getText()).join(', ')}>` : '';
    const members = decl.members.map((m) => squash(m.getText()).replace(/[;,]$/, '')).join('; ');
    body = `\`${name}${tp}\` { ${members} }`;
  } else if (ts.isTypeAliasDeclaration(decl)) {
    const tp = decl.typeParameters ? `<${decl.typeParameters.map((t) => t.getText()).join(', ')}>` : '';
    body = `\`${name}${tp}\` = \`${squash(decl.type.getText())}\``;
  } else if (ts.isClassDeclaration(decl)) {
    body = `\`${name}\` (class)`;
  } else if (ts.isEnumDeclaration(decl)) {
    body = `\`${name}\` (enum) { ${decl.members.map((m) => m.name.getText()).join(', ')} }`;
  } else if (isValue && calls.length > 0) {
    // Overloads: show every public signature, one per line item separated by " | ".
    body = calls.map((s) => `\`${sig(s)}\``).join(' · ');
  } else if (isValue) {
    body = `\`${name}\`: \`${squash(checker.typeToString(type, decl, ts.TypeFormatFlags.NoTruncation))}\``;
  } else {
    body = `\`${name}\``;
  }
  return { name, line: clip(`- ${body}${tail}`) };
}

/** Lines (sorted by export name) describing every export of the module at `entry`. */
export function describeEntry(entry, options = DEFAULT_OPTIONS) {
  const program = ts.createProgram([entry], options);
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(entry);
  const moduleSymbol = source && checker.getSymbolAtLocation(source);
  if (!moduleSymbol) return [];
  return checker
    .getExportsOfModule(moduleSymbol)
    .map((s) => describeSymbol(checker, s))
    .filter(Boolean)
    .sort(byName)
    .map((e) => e.line);
}

/** Markdown for `modules` (kept in the given order): one `##` each, one line per export. */
export function renderDigest(modules) {
  const head = [
    '# API digest',
    '',
    'Generated by `npm run api` from the public exports of each module; do not edit. Signatures plus the first JSDoc line.',
    '',
  ];
  const sections = modules.map((m) => `## \`${m.name}\`\n\n${m.lines.length ? m.lines.join('\n') : '_(no exports yet)_'}\n`);
  return `${head.join('\n')}\n${sections.join('\n')}`;
}

function projectOptions() {
  const cfgPath = join(ROOT, 'tsconfig.json');
  const cfg = ts.readConfigFile(cfgPath, ts.sys.readFile);
  return ts.parseJsonConfigFileContent(cfg.config, ts.sys, ROOT).options;
}

/** Entry points: src/core/<module>/index.ts (not _private) then src/ui/index.ts. */
export function entryPoints() {
  const coreDir = join(ROOT, 'src', 'core');
  const core = readdirSync(coreDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('_') && existsSync(join(coreDir, d.name, 'index.ts')))
    .map((d) => ({ name: `core/${d.name}`, file: join(coreDir, d.name, 'index.ts') }))
    .sort(byName);
  return [...core, { name: 'ui', file: join(ROOT, 'src', 'ui', 'index.ts') }];
}

export function generate() {
  const options = projectOptions();
  return renderDigest(entryPoints().map((e) => ({ name: e.name, lines: describeEntry(e.file, options) })));
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = generate();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== next) {
      console.error('docs/api.md is stale. Run `npm run api` and commit the result.');
      process.exitCode = 1;
    } else {
      console.log('docs/api.md is up to date.');
    }
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote docs/api.md (${Buffer.byteLength(next)} bytes)`);
  }
}

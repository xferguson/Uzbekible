#!/usr/bin/env node
// C4 build: top-200 lemmas (content/items/freq-0001-0200) + morph.mjs → content/items/inflected-0001-0200.yaml.
// Usage: node content/sources/inflected/build.mjs   (no network; see README.md)
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml, Document, visit, isPair, isScalar } from 'yaml';
import { NOUN_FORMS, VERB_FORMS, uzNoun, trNoun, uzVerb, trVerb } from './morph.mjs';
import { validateItems } from '../cognates/lib.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const items = join(here, '..', '..', 'items');

/** Lemma ids with regular inflection in both languages and a non-false-friend Turkish partner. */
const NOUNS =
  `ish odam kun yer yil til uy yoʻl bosh ona koʻz kitob qiz kishi soʻz suv yosh ota maktab doʻst
  dunyo davlat xalq hayot oy soat sabab mamlakat mashina yuz`.split(/\s+/);
const VERBS =
  `boʻlmoq olmoq demoq kelmoq bermoq koʻrmoq qolmoq ketmoq etmoq bilmoq bormoq chiqmoq turmoq
  qoʻymoq ishlamoq kirmoq oʻqimoq soʻramoq yashamoq yozmoq boshlamoq yurmoq sotmoq eshitmoq oʻtirmoq ochmoq
  oʻrganmoq koʻrsatmoq tushmoq tutmoq koʻrinmoq qurmoq urmoq chiqarmoq oʻlmoq yetmoq`.split(/\s+/);

const lemmas = [1, 101].flatMap((r) => {
  const n = `freq-${String(r).padStart(4, '0')}-${String(r + 99).padStart(4, '0')}.yaml`;
  return parseYaml(readFileSync(join(items, n), 'utf8'));
});
const byLatn = new Map(lemmas.map((l) => [l.uz.latn, l]));

const slug = (s) =>
  s
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[ʻʼ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const gloss = (l, label) => `${l.glossEn.split(/[,;]/)[0].trim()} (${label})`;
const out = [];
const seen = new Set(lemmas.map((l) => l.id));

function emit(l, tr, form, [latn, cyrl], trText, extraTags) {
  const src = tr;
  // Same convention as the lemma ids: on a slug clash (oldim from olmoq and oʻlmoq) the later one gets its rank.
  let id = `uz-${slug(latn)}`;
  if (seen.has(id)) id = `${id}-${l.freqRank}`;
  if (seen.has(id)) throw new Error(`id clash: ${id}`);
  seen.add(id);
  out.push({
    id,
    uz: { latn, cyrl },
    freqRank: l.freqRank,
    form: 'inflected',
    lemma: l.id,
    suffixes: [...form.suffixes],
    pos: l.pos,
    glossEn: gloss(l, form.label),
    sources: [
      {
        lang: 'tr',
        text: trText,
        relation: src.relation,
        confidence: src.confidence,
        ...(src.correspondence
          ? { correspondence: src.correspondence.filter((c) => c !== 'mak>moq') }
          : {}),
        ref: `lemma:${l.id}; rule:C4-morph`,
      },
    ],
    tags: [form.tag, ...extraTags],
  });
}

for (const [list, kind] of [
  [NOUNS, 'noun'],
  [VERBS, 'verb'],
]) {
  for (const latn of list) {
    const l = byLatn.get(latn);
    if (!l) throw new Error(`unknown lemma ${latn}`);
    if (l.freqRank > 200) throw new Error(`${latn} outside top 200`);
    const tr = l.sources.find((s) => s.lang === 'tr' && s.relation !== 'false-friend');
    if (!tr) throw new Error(`${latn}: no usable Turkish partner`);
    if (kind === 'noun') {
      const u = uzNoun(l.uz.latn, l.uz.cyrl);
      const t = trNoun(tr.text);
      for (const f of NOUN_FORMS) emit(l, tr, f, u[f.key], t[f.key], []);
    } else {
      const u = uzVerb(l.uz.latn, l.uz.cyrl);
      const t = trVerb(tr.text);
      for (const f of VERB_FORMS)
        emit(l, tr, f, u[f.key], t[f.key], f.key === 'continuous' ? ['divergent-suffix'] : []);
    }
  }
}

const errors = validateItems(out);
if (errors.length) throw new Error(`invalid items:\n${errors.join('\n')}`);

const doc = new Document(out);
visit(doc, {
  Pair(_, pair) {
    if (
      isPair(pair) &&
      isScalar(pair.key) &&
      ['uz', 'correspondence', 'tags', 'suffixes'].includes(pair.key.value)
    )
      pair.value.flow = true;
  },
});
const header =
  '# Inflected pairs for the top-200 lemmas (task C4): plural, possessive 1sg/2sg, locative, dative, ablative,\n' +
  '# past -di and present continuous. Generated by content/sources/inflected/build.mjs from morph.mjs: edit the rules\n' +
  '# or the lemma lists there, then rebuild. Items tagged divergent-suffix differ in the suffix itself (-yap- vs -iyor-).\n';
writeFileSync(join(items, 'inflected-0001-0200.yaml'), header + doc.toString({ lineWidth: 0 }));
console.log(`wrote ${out.length} items (${NOUNS.length} nouns, ${VERBS.length} verbs)`);

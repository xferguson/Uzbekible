import { CONFIDENCES, type Confidence, type Item } from './schema.ts';
import type { Issue } from './validate.ts';

const RANK: Record<Confidence, number> = { low: 0, medium: 1, high: 2 };

/** An item is as trustworthy as its weakest source; no sources at all counts as low. */
export function itemConfidence(item: Item): Confidence {
  if (item.sources.length === 0) return 'low';
  return item.sources.reduce<Confidence>(
    (min, s) => (RANK[s.confidence] < RANK[min] ? s.confidence : min),
    'high',
  );
}

const cell = (s: string): string => s.replaceAll('|', '\\|');
const title = (c: Confidence): string => c[0]!.toUpperCase() + c.slice(1);

function row(item: Item): string {
  const sources = item.sources.map((s) => `${s.lang}: ${s.text} (${s.relation})`).join('; ') || '—';
  const refs = item.sources.map((s) => s.ref).join('; ') || '—';
  return `| ${item.id} | ${item.uz.latn} / ${item.uz.cyrl} | ${cell(item.glossEn)} | ${cell(sources)} | ${cell(refs)} |`;
}

/** docs/content/review.md: items grouped by confidence (lowest first) for spot-checking, plus validator warnings. */
export function renderReview(items: readonly Item[], issues: readonly Issue[]): string {
  const sorted = [...items].sort((a, b) => a.freqRank - b.freqRank || a.id.localeCompare(b.id));
  const lines = [
    '# Content review',
    '',
    'Generated by `npm run content:review`. Do not edit by hand.',
    '',
    `${sorted.length} items.`,
    '',
  ];
  for (const level of [...CONFIDENCES].reverse()) {
    const group = sorted.filter((i) => itemConfidence(i) === level);
    lines.push(`## ${title(level)} confidence (${group.length})`, '');
    if (group.length) {
      lines.push(
        '| id | Uzbek | gloss | sources | refs |',
        '|---|---|---|---|---|',
        ...group.map(row),
        '',
      );
    }
  }
  const warn = issues.filter((i) => i.severity === 'warning');
  lines.push(`## Validator warnings (${warn.length})`, '');
  for (const w of [...warn].sort(
    (a, b) => a.code.localeCompare(b.code) || a.id.localeCompare(b.id),
  ))
    lines.push(`- \`${w.code}\` ${w.id}: ${w.message}`);
  return lines.join('\n') + '\n';
}
